"""
Builds sql/install/03_world_data.sql from open data:
  * Natural Earth 1:110m admin-0 countries (public domain) via the world-atlas npm package
  * GeoNames cities with population >= 15,000 (CC BY 4.0) via the all-the-cities npm package

Run from the repo root:  python tools/build_world_data.py <countries.geojson> <cities.json>
You only need this if you want to regenerate the data script; the generated file ships with the tool.
"""
import json, sys, pathlib
from shapely.geometry import shape, Polygon, MultiPolygon
from shapely.geometry.polygon import orient
from shapely.validation import make_valid

root = pathlib.Path(__file__).resolve().parents[1]
countries_path, cities_path = sys.argv[1], sys.argv[2]
out = root / "sql" / "install" / "03_world_data.sql"


def q(s):
    return "N'" + str(s).replace("'", "''") + "'"


def ring_wkt(coords):
    return "(" + ", ".join(f"{x:.5f} {y:.5f}" for x, y in coords) + ")"


def poly_wkt(p: Polygon):
    p = orient(p, sign=1.0)  # exterior CCW, holes CW: the geography left-hand rule
    rings = [ring_wkt(p.exterior.coords)] + [ring_wkt(r.coords) for r in p.interiors]
    return "(" + ", ".join(rings) + ")"


def to_wkt(geom):
    if not geom.is_valid:
        geom = make_valid(geom)
    polys = []
    if isinstance(geom, Polygon):
        polys = [geom]
    elif isinstance(geom, MultiPolygon):
        polys = list(geom.geoms)
    else:  # GeometryCollection after make_valid: keep the areal parts
        for g in getattr(geom, "geoms", []):
            if isinstance(g, Polygon):
                polys.append(g)
            elif isinstance(g, MultiPolygon):
                polys.extend(g.geoms)
    polys = [p for p in polys if p.area > 0]
    if len(polys) == 1:
        return "POLYGON " + poly_wkt(polys[0])
    return "MULTIPOLYGON (" + ", ".join(poly_wkt(p) for p in polys) + ")"


lines = [
    "/* ==========================================================================",
    "   Spatial Studio - world data (generated by tools/build_world_data.py)",
    "   Countries : Natural Earth 1:110m admin-0 (public domain) via world-atlas",
    "   Cities    : GeoNames cities15000 (CC BY 4.0, www.geonames.org) via all-the-cities",
    "   ========================================================================== */",
    "USE SpatialStudio;",
    "GO",
    "SET NOCOUNT ON;",
    "TRUNCATE TABLE world.CountryStage;",
    "GO",
]

fc = json.load(open(countries_path, encoding="utf-8"))
rows = []
for i, f in enumerate(fc["features"], start=1):
    name = f["properties"].get("name", f"Country {i}")
    iso = f.get("id")
    iso = int(iso) if iso not in (None, "") and str(iso).isdigit() else None
    wkt = to_wkt(shape(f["geometry"]))
    rows.append(f"({i}, {q(name)}, {iso if iso is not None else 'NULL'}, {q(wkt)})")

for b in range(0, len(rows), 20):
    lines.append("INSERT world.CountryStage (CountryId, Name, IsoN3, Wkt) VALUES")
    lines.append(",\n".join(rows[b:b + 20]) + ";")
lines.append("GO")

cities = json.load(open(cities_path, encoding="utf-8"))
lines.append("TRUNCATE TABLE world.CityStage;")
crow = []
for cid, name, cc, pop, lon, lat, fcode in cities:
    crow.append(f"({int(cid)}, {q(name)}, '{cc}', {int(pop)}, {lon:.5f}, {lat:.5f}, '{fcode}')")
for b in range(0, len(crow), 1000):
    lines.append("INSERT world.CityStage (CityId, Name, CountryCode, Population, Lon, Lat, FeatureCode) VALUES")
    lines.append(",\n".join(crow[b:b + 1000]) + ";")
    lines.append("GO")

out.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"wrote {out} ({out.stat().st_size/1e6:.1f} MB): {len(rows)} countries, {len(crow)} cities")
