LAG_MIN = 40


def santa_times():
    """Each city at local midnight; cities sharing an offset spread across that hour (westward order)."""
    stops, by_off = [], {}
    for c in SANTA:
        by_off.setdefault(c[3], []).append(c)
    base = dt.datetime(2026, 12, 25, 0, 0)
    for off in sorted(by_off, reverse=True):
        group = sorted(by_off[off], key=lambda c: c[2], reverse=True)  # east to west within the band
        n = len(group)
        for j, (name, lat, lon, o) in enumerate(group):
            t = base - dt.timedelta(hours=o) + dt.timedelta(minutes=round((j - (n - 1) / 2) * 50 / max(n, 1)))
            stops.append((name, lat, lon, o, t))
    stops.sort(key=lambda s: s[4])
    return stops


def main():
    stops = santa_times()
    depart = stops[0][4] - dt.timedelta(minutes=30)
    home = stops[-1][4] + dt.timedelta(minutes=60)
    route = [{"city": "North Pole", "lat": 90, "lon": 0, "utc": depart.isoformat() + "Z"}]
    route += [{"city": s[0], "lat": s[1], "lon": s[2], "offset": s[3], "utc": s[4].isoformat() + "Z", "gag": GAGS.get(s[0])} for s in stops]
    route += [{"city": "North Pole", "lat": 90, "lon": 0, "utc": home.isoformat() + "Z"}]
    data = {
        "lagMinutes": LAG_MIN,
        "escapades": [
            {"day": d, "place": p, "lat": la, "lon": lo, "title": t, "scheme": s, "outcome": o, "mood": m, "brian": b,
             "log": [{"t": a, "text": x} for a, x in log]}
            for d, p, la, lo, t, s, o, m, b, log in ESCAPADES],
        "santa": route,
    }
    (HERE / "data.json").write_text(json.dumps(data, ensure_ascii=False))
    print(len(ESCAPADES), "escapades;", len(route), "Santa stops; depart", depart, "home", home)
    return data


